#!/usr/bin/env python3
"""Regenerate include/wa_tokens.h from upstream Baileys WABinary/constants.ts.

Pinned to a known Baileys commit so the token table stays in sync with the
protocol version we implement against. Run:

    python3 tools/gen_tokens.py [--input path/to/constants.ts]

If --input is omitted, the script downloads the pinned commit from GitHub.
"""
import re
import sys
import urllib.request

PINNED_COMMIT = "74af8eee102e088d55bef3d1e181a8e548bcf32"
URL = (
    "https://github.com/WhiskeySockets/Baileys/raw/"
    f"{PINNED_COMMIT}/src/WABinary/constants.ts"
)

HEADER_PREAMBLE = """/* AUTO-GENERATED by tools/gen_tokens.py — do not edit by hand.
 * Source: Baileys src/WABinary/constants.ts @ %s
 * Single-byte token table + double-byte (4-dict) token table.
 */
#ifndef WA_TOKENS_H
#define WA_TOKENS_H

#include <stddef.h>
#include <string.h>

"""


def extract_array(src, name):
    i = src.find("export const " + name)
    if i < 0:
        raise SystemExit(f"array {name} not found")
    j = src.find("[", i)
    depth = 0
    k = j
    while True:
        c = src[k]
        if c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                break
        elif c == "'":
            # skip string literal (no escaped quotes in this file)
            k = src.find("'", k + 1)
        k += 1
    return src[j : k + 1]


def parse_strings(array_src):
    return re.findall(r"'((?:[^'\\\\]|\\\\.)*)'", array_src)


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    inp = None
    for i, a in enumerate(sys.argv[1:]):
        if a == "--input":
            inp = sys.argv[i + 2]
    if inp:
        src = open(inp).read()
    else:
        print(f"downloading {URL} ...", file=sys.stderr)
        src = urllib.request.urlopen(URL).read().decode("utf-8")

    single = parse_strings(extract_array(src, "SINGLE_BYTE_TOKENS"))
    dbl_src = extract_array(src, "DOUBLE_BYTE_TOKENS")
    # split top-level dicts: find each [...] at depth 1
    dicts = []
    depth = 0
    cur = None
    instr = False
    for idx, ch in enumerate(dbl_src):
        if ch == "'" and dbl_src[idx - 1] != "\\":
            instr = not instr
        if instr:
            continue
        if ch == "[":
            depth += 1
            if depth == 2:
                cur = idx
        elif ch == "]":
            if depth == 2:
                dicts.append(parse_strings(dbl_src[cur : idx + 1]))
            depth -= 1

    out = [HEADER_PREAMBLE % PINNED_COMMIT]
    out.append(f"/* {len(single)} single-byte tokens (index 0..{len(single)-1}) */\n")
    out.append("static const char *WA_SINGLE_TOKENS[] = {\n")
    for s in single:
        out.append(f"    {c_str(s)},\n")
    out.append("};\n")
    out.append(
        f"static const size_t WA_SINGLE_TOKENS_LEN = sizeof(WA_SINGLE_TOKENS)/sizeof(WA_SINGLE_TOKENS[0]);\n\n"
    )
    for di, d in enumerate(dicts):
        out.append(f"/* double-byte dict {di}: {len(d)} tokens */\n")
        out.append(f"static const char *WA_DOUBLE_TOKENS_{di}[] = {{\n")
        for s in d:
            out.append(f"    {c_str(s)},\n")
        out.append("};\n")
        out.append(
            f"static const size_t WA_DOUBLE_TOKENS_{di}_LEN = "
            f"sizeof(WA_DOUBLE_TOKENS_{di})/sizeof(WA_DOUBLE_TOKENS_{di}[0]);\n\n"
        )
    out.append("""/* Token lookup: returns 1 + sets dict/index on hit, 0 on miss.
 * dict = -1  -> single-byte token; dict 0..3 -> double-byte dict. */
static inline int wa_token_lookup(const char *s, int *dict, int *index) {
    size_t i;
    if (!s || !*s) return 0;
    for (i = 0; i < WA_SINGLE_TOKENS_LEN; i++) {
        if (WA_SINGLE_TOKENS[i][0] && strcmp(WA_SINGLE_TOKENS[i], s) == 0) {
            *dict = -1; *index = (int)i; return 1;
        }
    }
#define WA_TRY_DICT(n) \\
    for (i = 0; i < WA_DOUBLE_TOKENS_##n##_LEN; i++) { \\
        if (strcmp(WA_DOUBLE_TOKENS_##n[i], s) == 0) { *dict = n; *index = (int)i; return 1; } \\
    }
    WA_TRY_DICT(0)
    WA_TRY_DICT(1)
    WA_TRY_DICT(2)
    WA_TRY_DICT(3)
#undef WA_TRY_DICT
    return 0;
}

/* Reverse lookup: dict=-1 single, else double. Returns "" on OOB. */
static inline const char *wa_token_string(int dict, int index) {
    if (dict < 0) {
        if (index >= 0 && (size_t)index < WA_SINGLE_TOKENS_LEN) return WA_SINGLE_TOKENS[index];
        return "";
    }
    switch (dict) {
    case 0: if (index >= 0 && (size_t)index < WA_DOUBLE_TOKENS_0_LEN) return WA_DOUBLE_TOKENS_0[index]; break;
    case 1: if (index >= 0 && (size_t)index < WA_DOUBLE_TOKENS_1_LEN) return WA_DOUBLE_TOKENS_1[index]; break;
    case 2: if (index >= 0 && (size_t)index < WA_DOUBLE_TOKENS_2_LEN) return WA_DOUBLE_TOKENS_2[index]; break;
    case 3: if (index >= 0 && (size_t)index < WA_DOUBLE_TOKENS_3_LEN) return WA_DOUBLE_TOKENS_3[index]; break;
    default: break;
    }
    return "";
}

#endif /* WA_TOKENS_H */
""")
    with open("include/wa_tokens.h", "w") as f:
        f.write("".join(out))
    print(f"wrote include/wa_tokens.h ({len(single)} single + {len(dicts)} dicts)")


if __name__ == "__main__":
    main()
